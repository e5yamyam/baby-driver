     * 3. **손님만 가리킨다.** "저 아래 개울이 반짝 하고 지나갔어" 는 개울이 없으면 거짓이다.
     *    창밖에 뭐가 있는지 우리는 모른다 — 아는 건 **손님이 지금 무엇을 하고 있는지**뿐이다.
     */
