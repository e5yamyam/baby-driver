/**
 * **본문 한 쪽.** 동화책은 1쪽부터 순서대로 읽는 것이다.
 *
 * ## 왜 이걸 새로 만들었나 (2026-10-31)
 * 전까지 이 앱은 **차에서 신호가 올 때마다 조각을 하나씩 골라 붙였다.**
 * 커브가 오면 커브 대사, 터널이 오면 터널 대사. 조각을 아무리 다듬어도
 * **순서가 없으니 책이 아니다** — 기승전결도, 읽던 자리도 없다.
 *
 * 기획서는 처음부터 "이야기가 먼저 서고 길은 그 이야기의 사건이 된다"고 썼는데,
 * 코드는 정확히 **반대로** 돌고 있었다. 그래서 뒤집는다.
 *
 * **책이 먼저다. 길은 박자다.**
 * 앱은 1쪽부터 순서대로 읽고, 차 신호는 두 가지만 한다 —
 * ⑴ **언제 다음 쪽을 넘길지** ⑵ **어느 쪽을 지금 읽으면 딱 맞는지**([fit]).
 *
 * @param fit  이 쪽이 **어울리는 길**. 굴 쪽은 터널에서 읽어야 맛이 산다.
 *             그 길이 안 오면 [Episode.WAIT_TURNS] 만큼 기다렸다 그냥 읽는다 —
 *             **책이 멈추면 안 되니까.** 길이 먼저 오면 그 자리에서 읽는다(동기화).
 * @param core 짧은 주행에서도 **빼지 않는 쪽**. 12분 등원길이면 이것만 읽는다.
 */
class BookPage(
    val text: String,
    val scene: SceneKind = SceneKind.ROAD,
    val fit: SceneKind? = null,
    val core: Boolean = false,
    /**
     * 3~4세용 한 호흡 판. **없으면 세 살에게는 그 쪽을 읽지 않는다**(단 [core] 는 읽는다).
     * 어릴수록 말수가 적어야 한다 — 세 살에게 12분에 열 마디는 소음이다.
     */
    val short: String? = null,
    /**
     * `{여기}` 를 쓰는 쪽에서, **아이가 아는 지명이 없을 때** 대신 읽는 문장.
     * 없으면 그 쪽을 통째로 건너뛴다 — **주소를 읽느니 안 읽는 게 낫다.**
     */
    val alt: String? = null,
    /**
     * **이 쪽에서 손님이 자란다.** 화면의 구름이 실제로 커진다([SceneView.growth]).
     *
     * 왜 쪽에 붙이나: 전에는 터널을 지날 때 코드가 알아서 키웠다. 그래서 본문이
     * "아주 조금 커졌어요!" 를 읽는 자리와 그림이 커지는 자리가 **서로 달랐다** —
     * 1화는 터널 분기를 안 지나므로 말만 커지고 그림은 그대로였다(2026-10-31 실측).
     * **커진다고 말하는 쪽에 붙이는 것**이 어긋나지 않는 유일한 방법이다.
     */
    val grow: Boolean = false,
    /**
     * **이 쪽에서 아이가 오늘 할 일을 받는다.** 화마다 딱 한 쪽이다.
     *
     * 왜 표시가 필요한가: 정차하면 [Episode.asks] 로 아이에게 한 번 묻는데, 그 물음이
     * **과제보다 먼저 나갈 수 있었다.** 2026-11-05 전사(세 살 65분): 46분에
     * "창밖에 반짝이는 게 몇 개나 보여?" 를 묻고, 49분에야 "반짝이는 거 하나 찾아 줘" 가 나왔다 —
     * 아이는 왜 세어야 하는지 모르는 채 세어야 했다. 묻는 말은 **할 일을 준 뒤**에만 뜻이 있다.
     */
    val quest: Boolean = false,
)

/**
 * **그 화의 과제.** 오늘 하루 모든 대사가 여기로 수렴한다.
 *
 * ## 왜 이게 필요한가 (2026-10-31)
 * 전까지는 신호 하나에 대사 하나를 매달아 뒀다 — 커브가 오면 늘 "{탈것}이 기울어",
 * 방지턱이면 늘 "파도야!". 문장이 커브에 둘, 방지턱에 하나뿐이라
 * **65분을 달리면 같은 말이 스무 번 나온다.** 그건 동화가 아니라 알림음이다.
 *
 * 진짜 동화는 **오늘 뭘 하러 가는지**가 있고, 길에서 생기는 일이 그 일을 돕거나 방해한다.
 * 시즌 1은 화마다 아이가 할 일이 이미 다르다 — 2화는 물을 찾고, 3화는 바람을 찾고,
 * 5화는 소리를 듣는다. 그런데 코드가 그걸 하나도 안 쓰고 있었다.
 *
 * 그래서 축을 바꿨다. **커브는 "기울어"가 아니라 "기울어 — 그러니까 지금 창밖에 물이 보여?"가 된다.**
 * 같은 커브가 2화와 5화에서 다른 말이 되고, 같은 화 안에서도 [looks] 를 돌려 쓰므로 안 겹친다.
 *
 * @param seek  오늘 찾는 것. **전부 차창 밖에 실제로 있는 것**이어야 한다 —
 *              없는 걸 찾으라고 하면 아이가 두 번째부터 안 본다.
 *              (코드가 읽지 않는다. 본문·과제를 쓸 때 보는 **메모**다.)
 * @param looks 사건이 났을 때 **과제로 이어 붙이는 꼬리.** 돌려 가며 쓴다.
 * @param asks  차가 조용할 때 **아이에게 묻고 기다리는 말.** 대답을 받지 않아도 된다 —
 *              묻는 것 자체가 아이에게 역할을 준다.
 * @param gain  한참 뒤에 "찾았다고 치고" 돌려주는 말. 아이가 뭘 했든 **헛되지 않게** 한다.
 */
