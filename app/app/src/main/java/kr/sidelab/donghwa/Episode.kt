     * 전에는 코드가 `화 번호 - 1` 로 깔았다. 줄거리가 쭉 자라기만 하면 맞는데,
     * **8화는 구름이 비가 되어 쏟아지는 화**다. 그런데 화면은 `8-1` 을 상한에 맞춰
     * **거의 다 큰 구름**을 그렸다 — 글은 "손톱만 한 구름" 이라고 읽는데(2026-11-05 전사).
     * 글과 그림이 다른 말을 하면 그림책이 아니다. **크기는 줄거리가 정한다.**
