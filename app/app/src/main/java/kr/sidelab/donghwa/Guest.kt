 * 동화에는 **누가 · 무엇을 하려고 · 어떻게 됐는지**가 있어야 한다.
 *
 * 그래서 출발할 때 배에 손님이 한 명 탄다. 손님에겐 가야 할 곳과 사정이 있고,
 * **우리 목적지가 곧 손님의 목적지**가 된다. 그러면 아이에게 할 일이 생긴다 —
 * "창밖을 보세요"가 아니라 "구름이 안 떨어지게 붙잡아 줘"가 된다.
 * 시키는 말은 몇 번 들으면 안 듣지만, 역할은 계속 한다.
 *
 * 손님이 날마다 바뀌므로 **같은 길을 두 번 가도 같은 이야기가 아니다.**
 *
